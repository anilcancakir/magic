import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:magic/src/cli/helpers/design_token_scanner.dart';
import 'package:path/path.dart' as p;

/// Writes [content] to [relativePath] under [root], creating directories.
void _write(Directory root, String relativePath, String content) {
  File(p.join(root.path, relativePath))
    ..createSync(recursive: true)
    ..writeAsStringSync(content);
}

void main() {
  group('DesignTokenScanner.stripComments', () {
    test('drops a line comment after code and keeps the code', () {
      expect(
        DesignTokenScanner.stripComments('final a = 1; // Colors.red\n'),
        'final a = 1; \n',
      );
    });

    test('drops doc comments', () {
      expect(
        DesignTokenScanner.stripComments(
          '/// Uses `Colors.red`.\nclass A {}\n',
        ),
        '\nclass A {}\n',
      );
    });

    test('drops a block comment across lines and keeps the line count', () {
      const source = 'a /* Colors.red\nColor(0xFF000000)\n*/ b\n';

      final stripped = DesignTokenScanner.stripComments(source);

      expect(stripped, 'a \n\n b\n');
    });

    test('tracks nested block comments', () {
      expect(
        DesignTokenScanner.stripComments('/* a /* b */ Colors.red */ c'),
        ' c',
      );
    });

    test('keeps // and /* inside a string and strips the real comment', () {
      expect(
        DesignTokenScanner.stripComments(
          "final url = 'https://x.dev/*'; // Colors.red",
        ),
        "final url = 'https://x.dev/*'; ",
      );
    });

    test('keeps string content, so a literal inside a string survives', () {
      expect(
        DesignTokenScanner.stripComments('final s = "Colors.red";'),
        'final s = "Colors.red";',
      );
    });

    test('honours escaped quotes', () {
      expect(
        DesignTokenScanner.stripComments(r"'it\'s // fine' + x // Colors.red"),
        r"'it\'s // fine' + x ",
      );
    });

    test('ends a raw string at the first quote, backslash included', () {
      expect(
        DesignTokenScanner.stripComments(r"r'C:\' // Colors.red"),
        r"r'C:\' ",
      );
    });

    test('tracks triple-quoted strings across lines', () {
      const source =
          "const s = '''\n// not a comment\n''';\n"
          'final c = 1; // Colors.red\n';

      expect(
        DesignTokenScanner.stripComments(source),
        "const s = '''\n// not a comment\n''';\nfinal c = 1; \n",
      );
    });

    test('tracks nested strings inside an interpolation', () {
      const source = r'''"${a ? 'x' : "y"} // kept" // Colors.red''';

      expect(
        DesignTokenScanner.stripComments(source),
        r'''"${a ? 'x' : "y"} // kept" ''',
      );
    });

    test('returns the source unchanged on an unterminated block comment', () {
      const source = 'a /* never closed\nColors.red\n';

      expect(DesignTokenScanner.stripComments(source), source);
    });
  });

  group('DesignTokenScanner.pattern', () {
    for (final literal in <String>[
      'Color(0xFF112233)',
      'Color.fromARGB(255, 1, 2, 3)',
      'Color.fromRGBO(1, 2, 3, 1)',
      'Color.from(alpha: 1, red: 0, green: 0, blue: 0)',
      'Colors.red',
      'MaterialColor(0xFF112233, {})',
    ]) {
      test('matches $literal', () {
        expect(DesignTokenScanner.pattern.hasMatch(literal), isTrue);
      });
    }

    for (final clean in <String>[
      'kBrandColors.first',
      'context.colors.primary',
      'ColorScheme.fromSeed(seedColor: seed)',
    ]) {
      test('does not match $clean', () {
        expect(DesignTokenScanner.pattern.hasMatch(clean), isFalse);
      });
    }
  });

  group('DesignTokenAllowlist.parse', () {
    final allowlist = DesignTokenAllowlist.parse(
      '# Generated code\n'
      '\n'
      '  lib/config/wind_theme.g.dart  | generated by design:sync\r\n'
      'lib/generated/ | generated tree\n'
      'lib/legacy.dart\n'
      ' | no path\n',
    );

    test('allows an exact file with surrounding whitespace trimmed', () {
      expect(allowlist.allows('lib/config/wind_theme.g.dart'), isTrue);
    });

    test('allows every path under a directory prefix', () {
      expect(allowlist.allows('lib/generated/a/b.dart'), isTrue);
    });

    test('accepts an entry without a reason', () {
      expect(allowlist.allows('lib/legacy.dart'), isTrue);
    });

    test('matches a file entry exactly, never as a prefix', () {
      expect(allowlist.allows('lib/legacy.dart.bak'), isFalse);
      expect(allowlist.allows('lib/config/other.dart'), isFalse);
    });

    test('a missing file loads as an empty allowlist', () {
      final empty = DesignTokenAllowlist.load(
        p.join(Directory.systemTemp.path, 'no-such-dir-x', 'allowlist'),
      );

      expect(empty.allows('lib/a.dart'), isFalse);
    });
  });

  group('DesignTokenScanner.scan', () {
    late Directory root;

    setUp(() {
      root = Directory.systemTemp.createTempSync('design_token_scanner_');
    });

    tearDown(() {
      if (root.existsSync()) root.deleteSync(recursive: true);
    });

    test('reports sorted lib hits with 1-based lines, skipping test/', () {
      _write(root, 'lib/b.dart', 'final x = 1;\nfinal c = Colors.red;\n');
      _write(root, 'lib/a/a.dart', 'final c = Color(0xFF112233);\n');
      _write(root, 'lib/readme.md', 'Colors.red\n');
      _write(root, 'test/a_test.dart', 'final c = Colors.red;\n');

      final hits = DesignTokenScanner.scan(
        root.path,
        DesignTokenAllowlist.parse(''),
      );

      expect(hits.map((hit) => '${hit.path}:${hit.line}'), <String>[
        'lib/a/a.dart:1',
        'lib/b.dart:2',
      ]);
    });

    test('skips allowlisted files', () {
      _write(root, 'lib/gen/theme.g.dart', 'final c = Colors.red;\n');

      final hits = DesignTokenScanner.scan(
        root.path,
        DesignTokenAllowlist.parse('lib/gen/ | generated\n'),
      );

      expect(hits, isEmpty);
    });

    test('does not follow a symbolic link under lib/', () {
      _write(root, 'lib/a/x.dart', 'final c = Colors.red;\n');
      Link('${root.path}/lib/a/up').createSync('..');

      final hits = DesignTokenScanner.scan(
        root.path,
        DesignTokenAllowlist.parse(''),
      );

      expect(hits.map((hit) => '${hit.path}:${hit.line}'), <String>[
        'lib/a/x.dart:1',
      ]);
    });

    test('returns no hits when lib/ is absent', () {
      expect(
        DesignTokenScanner.scan(root.path, DesignTokenAllowlist.parse('')),
        isEmpty,
      );
    });
  });
}
